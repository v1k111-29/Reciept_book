#!/usr/bin/env bash
# Copy the canonical TS contracts into each TS package. OWNER: P1.
# Run after editing contracts/contracts.ts (and after scripts/export_schema.py).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
for pkg in chaincode gateway frontend; do
  dest="$ROOT/$pkg/src/generated"
  mkdir -p "$dest"
  for f in contracts.ts parity.ts; do
    { echo "// GENERATED by scripts/sync_ts_contracts.sh from contracts/$f. DO NOT EDIT."; cat "$ROOT/contracts/$f"; } > "$dest/$f"
  done
  cp "$ROOT/contracts/contracts.schema.json" "$dest/contracts.schema.json"
  echo "synced -> $pkg/src/generated/"
done
