"""The generated TS copies must equal their sources. Owner: P1.

If this fails: run `bash scripts/sync_ts_contracts.sh` and commit. Never hand-edit
<package>/src/generated/ (CODEOWNERS gives those files to P1).
"""

from __future__ import annotations

from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
HEADER = "// GENERATED by scripts/sync_ts_contracts.sh from contracts/{name}. DO NOT EDIT.\n"


@pytest.mark.parametrize("pkg", ["chaincode", "gateway", "frontend"])
@pytest.mark.parametrize("name", ["contracts.ts", "parity.ts"])
def test_generated_ts_matches_source(pkg: str, name: str) -> None:
    src = (ROOT / "contracts" / name).read_text(encoding="utf-8")
    got = (ROOT / pkg / "src" / "generated" / name).read_text(encoding="utf-8")
    assert got == HEADER.format(name=name) + src, f"{pkg}/src/generated/{name} is stale"


@pytest.mark.parametrize("pkg", ["chaincode", "gateway", "frontend"])
def test_generated_schema_matches_source(pkg: str) -> None:
    src = (ROOT / "contracts" / "contracts.schema.json").read_text(encoding="utf-8")
    got = (ROOT / pkg / "src" / "generated" / "contracts.schema.json").read_text(encoding="utf-8")
    assert got == src, f"{pkg}/src/generated/contracts.schema.json is stale"
